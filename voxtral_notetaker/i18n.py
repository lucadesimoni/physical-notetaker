LANGUAGES = ('de', 'en')


def normalize(lang: str) -> str:
    return 'en' if (lang or '').lower().startswith('en') else 'de'


def t(key: str, lang: str = 'de', **kwargs) -> str:
    """Translated text; falls back to German, then to the key itself"""
    text = TEXTS[normalize(lang)].get(key) or TEXTS['de'].get(key) or key
    return text.format(**kwargs) if kwargs else text
